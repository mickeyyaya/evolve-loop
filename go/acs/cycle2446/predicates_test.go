func TestC2446_007_TheClaudeNotesGainExactlyOneLineAndLoseNone(t *testing.T) {
	root := acsassert.RepoRoot(t)
	out, _, code, err := acsassert.SubprocessOutput("git", "-C", root, "diff", "--numstat", diffBase(t), "--", claudeNotes)
	if err != nil || code != 0 {
		t.Fatalf("git diff exit=%d: %v", code, err)
	}
	fields := strings.Fields(out)
	if len(fields) < 3 {
		t.Fatalf("RED: %s has no change against the base, want one added line", claudeNotes)
	}
	added, addErr := strconv.Atoi(fields[0])
	removed, rmErr := strconv.Atoi(fields[1])
	if addErr != nil || rmErr != nil {
		t.Fatalf("numstat not numeric: %q", out)
	}
	if added != 1 || removed != 0 {
		t.Errorf("%s changed by +%d -%d lines, want +1 -0", claudeNotes, added, removed)
	}
}

