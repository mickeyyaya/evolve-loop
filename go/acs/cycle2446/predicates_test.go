func repoText(t *testing.T, rel string) string {
	t.Helper()
	abs := filepath.Join(acsassert.RepoRoot(t), filepath.FromSlash(rel))
	raw, readErr := os.ReadFile(abs)
	if readErr != nil {
		t.Fatalf("RED: cannot read %s (%v)", rel, readErr)
	}
	return string(raw)
}

func steFindings(t *testing.T, rel string) []string {
	t.Helper()
	words, err := stelint.LoadStandard(acsassert.RepoRoot(t))
	if err != nil {
		t.Fatalf("the STE standard did not load: %v", err)
	}
	var report []string
	for _, finding := range stelint.Check([]byte(repoText(t, rel)), stelint.Options{Words: words}) {
		if finding.IsSkipNotice() {
			continue
		}
		report = append(report, fmt.Sprintf("%s:%d [%s] %s", rel, finding.Line, finding.Rule, finding.Message))
	}
	return report
}

func researchNote(t *testing.T) (rel, text string) {
	t.Helper()
	researchDir := filepath.Join(acsassert.RepoRoot(t), "docs", "research")
	entries, readErr := os.ReadDir(researchDir)
	if readErr != nil {
		t.Fatalf("RED: docs/research cannot be listed: %v", readErr)
	}
	var named []string
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".md") {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(researchDir, entry.Name()))
		if err == nil && strings.Contains(string(raw), itemMarker) {
			named = append(named, "docs/research/"+entry.Name())
		}
	}
	if len(named) != 1 {
		t.Fatalf("RED: want one docs/research note that names %s, found %d: %v", itemMarker, len(named), named)
	}
	return named[0], repoText(t, named[0])
}

func diffBase(t *testing.T) string {
	t.Helper()
	root := acsassert.RepoRoot(t)
	if _, _, code, _ := acsassert.SubprocessOutput("git", "-C", root, "rev-parse", "--verify", "--quiet", "origin/main"); code != 0 {
		return "HEAD"
	}
	out, _, code, err := acsassert.SubprocessOutput("git", "-C", root, "merge-base", "HEAD", "origin/main")
	if err != nil || code != 0 || strings.TrimSpace(out) == "" {
		return "HEAD"
	}
	return strings.TrimSpace(out)
}

func changedFiles(t *testing.T, scope string) []string {
	t.Helper()
	root := acsassert.RepoRoot(t)
	changed, _, code, err := acsassert.SubprocessOutput("git", "-C", root, "diff", "--name-only", diffBase(t), "--", scope)
	if err != nil || code != 0 {
		t.Fatalf("git diff exit=%d: %v", code, err)
	}
	untracked, _, _, _ := acsassert.SubprocessOutput("git", "-C", root, "ls-files", "--others", "--exclude-standard", "--", scope)
	return strings.Fields(changed + "\n" + untracked)
}

func watermarkBullets(t *testing.T) []string {
	t.Helper()
	var bullets []string
	for _, line := range strings.Split(repoText(t, claudeNotes), "\n") {
		if strings.HasPrefix(line, "- ") && strings.Contains(strings.ToLower(line), "watermark") {
			bullets = append(bullets, line)
		}
	}
	return bullets
}

func personaVerdict(text, persona string) (verdict, reason string) {
	for _, line := range strings.Split(text, "\n") {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, "|") || !strings.Contains(trimmed, persona) {
			continue
		}
		cells := strings.Split(strings.Trim(trimmed, "|"), "|")
		if len(cells) < 3 {
			continue
		}
		return strings.TrimSpace(cells[1]), strings.TrimSpace(cells[len(cells)-1])
	}
	return "", ""
}

func TestC2446_001_TheNoteNamesTheItemTheSourceTheSnapshotAndTheReadAtTheLinkAndCallsThePageUntrustedData(t *testing.T) {
	rel, text := researchNote(t)
	if _, _, code, _ := acsassert.SubprocessOutput("git", "-C", acsassert.RepoRoot(t), "check-ignore", "-q", rel); code != 1 {
		t.Errorf("%s is ignored by git and would be dropped at ship (check-ignore exit code %d, want 1)", rel, code)
	}
	if !itemIDInNoteBody.MatchString(text) {
		t.Errorf("the note does not name the full item id practice-claude-model-release-notes-%s-<stamp>", itemMarker)
	}
	for _, need := range []string{sourceURL, snapshotRef, adrNumber} {
		if !strings.Contains(text, need) {
			t.Errorf("the note does not name %s", need)
		}
	}
	if !readAtLink.MatchString(text) {
		t.Errorf("the note does not state that the source was read at its link")
	}
	if !strings.Contains(strings.ToLower(text), "untrusted data") {
		t.Errorf("the note does not say that the release-note text is untrusted data")
	}
}

func TestC2446_002_TheNoteExplainsEachChangedLineAsAFactRowAndCopiesNoReleaseNoteSentence(t *testing.T) {
	_, text := researchNote(t)
	rows := findingRow.FindAllString(text, -1)
	if len(rows) < 4 {
		t.Fatalf("RED: the note explains %d lines in F rows, want at least 4", len(rows))
	}
	joined := strings.ToLower(strings.Join(rows, "\n"))
	topics := append([]string{"watermark", "authenticate"}, samplingParameters...)
	for _, model := range watermarkModels {
		topics = append(topics, strings.ToLower(model))
	}
	for _, topic := range topics {
		if !strings.Contains(joined, topic) {
			t.Errorf("no F row covers %q", topic)
		}
	}
	if !pageChromeWord.MatchString(strings.Join(rows, "\n")) {
		t.Errorf("no F row says that the cut-off Authenticate line is page text and not a rule")
	}
	if hit := copiedSentence.FindString(text); hit != "" {
		t.Errorf("the note copies release-note text instead of explaining it: %q", hit)
	}
}

func TestC2446_003_TheNoteHoldsNoPlaceholderFollowsNoPageTextAsARuleAndNeverClaimsFable52OrMythos52CarryTheWatermark(t *testing.T) {
	_, text := researchNote(t)
	if placeholder.MatchString(text) {
		t.Errorf("the note holds a placeholder word")
	}
	if hit := followsAsRule.FindString(text); hit != "" {
		t.Errorf("the note treats page text as a rule: %q", hit)
	}
	for _, line := range strings.Split(text, "\n") {
		lower := strings.ToLower(line)
		if !strings.Contains(lower, "watermark") {
			continue
		}
		if (strings.Contains(lower, "fable") || strings.Contains(lower, "mythos")) && !negatedLine.MatchString(line) {
			t.Errorf("the note claims the watermark covers Fable 5.2 or Mythos 5.2: %q", line)
		}
	}
}

func TestC2446_004_EachCorePersonaGetsANoChangeVerdictWithAReasonAndTheDecisionNamesTheOneNotesBullet(t *testing.T) {
	_, text := researchNote(t)
	if !noPersonaChange.MatchString(text) {
		t.Fatalf("RED: the note does not state that no persona or prompt changes")
	}
	for _, persona := range corePersonas {
		verdict, reason := personaVerdict(text, persona)
		if verdict == "" {
			t.Errorf("no table row gives a verdict for %s", persona)
			continue
		}
		if !strings.Contains(strings.ToLower(verdict), "no change") {
			t.Errorf("the verdict of %s is not a no-change verdict: %q", persona, verdict)
		}
		if reason == "" {
			t.Errorf("the verdict row of %s has no reason", persona)
		}
	}
	if personaChanges.MatchString(text) {
		t.Errorf("a verdict row proposes a persona change although the proposal changes none")
	}
	if !decisionBecause.MatchString(text) {
		t.Errorf("no Decision line states its reason with because")
	}
	if !notesBulletLine.MatchString(text) {
		t.Errorf("no line states that %s gets one added bullet", claudeNotes)
	}
	if !strings.Contains(strings.ToLower(text), "no persona sets") && !strings.Contains(strings.ToLower(text), "no phase prompt or persona sets") {
		t.Errorf("the note does not give the reason that no persona sets temperature, top_p or top_k")
	}
}

func TestC2446_005_TheClaudeNotesHoldExactlyOneWatermarkBulletThatNamesTheFourModelsAndTheThreeSamplingParameters(t *testing.T) {
	bullets := watermarkBullets(t)
	if len(bullets) != 1 {
		t.Fatalf("RED: want exactly one watermark bullet in %s, found %d", claudeNotes, len(bullets))
	}
	bullet := bullets[0]
	for _, model := range watermarkModels {
		if !strings.Contains(bullet, model) {
			t.Errorf("the watermark bullet does not name %s", model)
		}
	}
	for _, param := range samplingParameters {
		if !strings.Contains(bullet, param) {
			t.Errorf("the watermark bullet does not name %s", param)
		}
	}
	if !prohibitionWord.MatchString(bullet) {
		t.Errorf("the watermark bullet gives no prohibition (do not, never or avoid)")
	}
	if !nonDefaultWord.MatchString(bullet) {
		t.Errorf("the watermark bullet does not say non-default")
	}
}

