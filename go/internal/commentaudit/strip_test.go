func TestStripDirs_RewritesAFileAtomicallyAndKeepsItsMode(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "p.go")
	if err := os.WriteFile(path, []byte("package p\n\n// F is f.\nfunc F() {}\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	if report, err := StripDirs([]string{dir}); err != nil || report.Files != 1 {
		t.Fatalf("StripDirs = (%+v, %v)", report, err)
	}

	info, err := os.Stat(path)
	if err != nil || info.Mode().Perm() != 0o600 {
		t.Errorf("mode = %v (%v), want the file's own 0600 kept", info.Mode().Perm(), err)
	}
	if entries, _ := os.ReadDir(dir); len(entries) != 1 {
		t.Errorf("dir holds %d entries, want only p.go: the rewrite must leave no temporary file", len(entries))
	}
}

