func strippedSource(t *testing.T, name, src string) string {
	t.Helper()
	out, err := StripComments(name, []byte(src))
	if err != nil {
		t.Fatalf("StripComments(%s): %v", name, err)
	}
	return string(out.Source)
}

func strippedKeepingDoc(t *testing.T, name, src string) StrippedFile {
	t.Helper()
	out, err := StripCommentsKeepingPackageDoc(name, []byte(src))
	if err != nil {
		t.Fatalf("StripCommentsKeepingPackageDoc(%s): %v", name, err)
	}
	return out
}

func writeFiles(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	for name, src := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(got)
}

