func TestStripComments_IsIdempotent(t *testing.T) {
	src := "package p // the package\n\n// F is f.\n//\n// Deprecated: use G.\nfunc F() {} // trailing\n\nfunc G() {}\n"

	once := strippedSource(t, "p.go", src)
	twice, err := StripComments("p.go", []byte(once))

	if err != nil || twice.Removed != 0 || string(twice.Source) != once {
		t.Errorf("second strip = (%q, %d, %v), want nothing left to remove from %q", twice.Source, twice.Removed, err, once)
	}
	if strings.Contains(once, "the package") || !strings.HasPrefix(once, "package p\n") {
		t.Errorf("stripped = %q, want the comment on the package line gone", once)
	}
}

