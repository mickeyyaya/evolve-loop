func TestDerivedConflictIn_ReadsTheMergedFile(t *testing.T) {
	wt := t.TempDir()
	conflict := "<<<<<<< HEAD\na\n=======\nb\n>>>>>>> lane\n"
	writeFile(t, filepath.Join(wt, cflags), "<!-- GENERATED:flag-index BEGIN -->\n"+conflict+"<!-- GENERATED:flag-index END -->\n")
	writeFile(t, filepath.Join(wt, "docs", "architecture", "signal-codes.md"), conflict+"<!-- GENERATED:signal-codes BEGIN -->\n<!-- GENERATED:signal-codes END -->\n")
	classify := derivedConflictIn(wt)
	cases := []struct {
		path, entry string
		ok          bool
	}{
		{cflags, "flag-index", true},
		{"docs/architecture/signal-codes.md", "", false},
		{"commands/deleted.md", "", false},
		{"skills/build/SKILL.md", "", false},
		{"go/internal/core/x.go", "", false},
	}
	for _, c := range cases {
		if entry, ok := classify(c.path); entry != c.entry || ok != c.ok {
			t.Errorf("classify(%q) = (%q, %v), want (%q, %v)", c.path, entry, ok, c.entry, c.ok)
		}
	}
}

func TestRebaseWithDerivedRegen_RegeneratesAnEntryOncePerStep(t *testing.T) {
	g := &scriptedGit{}
	g.respond = func(args []string) (string, int, error) {
		j := joined(args)
		switch {
		case strings.HasPrefix(j, "diff --name-only --diff-filter=U"):
			return "commands/a.md\x00commands/b.md\x00" + cflags + "\x00", 0, nil
		case strings.HasPrefix(j, "ls-files "):
			return "commands/a.md\x00", 0, nil
		case j == "rebase main":
			return "", 1, nil
		}
		return "", 0, nil
	}
	regen, got := recordingRegen("")

	ok, conflicts := rebaseWithDerivedRegen(context.Background(), "/wt", g.capture, regen, derivedEntryOf)

	if !ok || len(conflicts) != 0 {
		t.Fatalf("rebase = (%v, %v), want (true, none)", ok, conflicts)
	}
	if want := "skill-projections,flag-index"; strings.Join(*got, ",") != want {
		t.Fatalf("regenerated = %v, want %s: one run per entry, not one per path", *got, want)
	}
}

