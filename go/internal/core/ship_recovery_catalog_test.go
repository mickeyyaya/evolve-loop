const commandStub = "commands/build.md"

func commandStubConflictRepo(t *testing.T) *gittest.Repo {
	t.Helper()
	repo := gittest.Fixture(t)
	stub := filepath.Join(repo.Dir, commandStub)
	writeFile(t, stub, "<!-- GENERATED by `evolve skills generate` from skills/build/SKILL.md — DO NOT EDIT. -->\nbase\n")
	repo.Git("add", "-A")
	repo.Git("commit", "-qm", "base")
	repo.Git("checkout", "-qb", "cycle")
	writeFile(t, stub, "<!-- GENERATED by `evolve skills generate` from skills/build/SKILL.md — DO NOT EDIT. -->\nlane\n")
	writeFile(t, filepath.Join(repo.Dir, "skills", "build", "SKILL.md"), "lane skill\n")
	repo.Git("add", "-A")
	repo.Git("commit", "-qm", "lane")
	repo.Git("checkout", "-q", "main")
	writeFile(t, stub, "<!-- GENERATED by `evolve skills generate` from skills/build/SKILL.md — DO NOT EDIT. -->\npeer\n")
	repo.Git("add", "-A")
	repo.Git("commit", "-qm", "peer")
	repo.Git("checkout", "-q", "cycle")
	return repo
}

func TestRebaseWithDerivedRegen_ACommandStubConflictRegenerates(t *testing.T) {
	repo := commandStubConflictRepo(t)
	regenerated := "<!-- GENERATED by `evolve skills generate` from skills/build/SKILL.md — DO NOT EDIT. -->\nregenerated\n"
	var asked []string
	regen := func(_ context.Context, wt, key string) error {
		asked = append(asked, key)
		return os.WriteFile(filepath.Join(wt, commandStub), []byte(regenerated), 0o644)
	}

	ok, conflicts := rebaseWithDerivedRegen(context.Background(), repo.Dir, gitCapture, regen, derivedConflictIn(repo.Dir))

	if !ok || len(conflicts) != 0 {
		t.Fatalf("a conflict only in a generated command stub must regenerate, not go to the debugger: got ok=%v conflicts=%v", ok, conflicts)
	}
	if got, _ := os.ReadFile(filepath.Join(repo.Dir, commandStub)); string(got) != regenerated {
		t.Errorf("%s = %q, want the regenerated stub", commandStub, got)
	}
	if status := repo.Git("status", "--porcelain"); status != "" {
		t.Errorf("worktree after the regenerated rebase = %q, want clean", status)
	}
	if base := repo.Git("merge-base", "main", "cycle"); base != repo.Git("rev-parse", "main") {
		t.Errorf("cycle is not rebased onto main: merge-base %s", base)
	}
	if strings.Join(asked, ",") == "" {
		t.Error("the regenerator never ran")
	}
}

