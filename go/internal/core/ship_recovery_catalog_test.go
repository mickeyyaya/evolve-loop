func TestNormalizeDerivedProjections_ChecksAStaleEntryWithTheWorktreeGenerator(t *testing.T) {
	if testing.Short() {
		t.Skip("compiles the worktree's cmd/evolve via `go run`; skipped under -short")
	}
	cases := []struct {
		name, changed, body, want string
	}{
		{"a path input", "skills/build/SKILL.md", "lane skill\n", "skills check"},
		{"a package in the skillcheck closure", "go/internal/skillcheck/s.go", "package skillcheck\n\nvar X = 1\n", "skills check"},
		{"a closure that go list cannot read falls back to the path inputs", "go/internal/skillcheck/s.go", "package skillcheck\n\nimport _ \"fakeevolve/nope\"\n", ""},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			repo := recordingWorktree(t)
			writeFile(t, filepath.Join(repo.Dir, filepath.FromSlash(c.changed)), c.body)

			(&Orchestrator{}).normalizeDerivedProjections(context.Background(), repo.Dir)

			raw, _ := os.ReadFile(filepath.Join(repo.Dir, "generator.log"))
			if got := loggedArgs(string(raw)); got != c.want {
				t.Fatalf("generator calls = %q, want %q", got, c.want)
			}
		})
	}
}

func loggedArgs(log string) string {
	var args []string
	for _, line := range strings.Split(strings.TrimSpace(log), "\n") {
		if _, a, ok := strings.Cut(line, "|"); ok {
			args = append(args, a)
		}
	}
	return strings.Join(args, ";")
}

