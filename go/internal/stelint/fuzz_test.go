package stelint_test

import (
	"reflect"
	"strings"
	"testing"

	"github.com/mickeyyaya/evolve-loop/go/internal/stelint"
)

var knownRules = map[string]bool{
	stelint.RuleSentence:         true,
	stelint.RuleParagraph:        true,
	stelint.RuleWord:             true,
	stelint.RuleSkippedGenerated: true,
}

func assertFindingInvariants(t *testing.T, src []byte, got []stelint.Finding) {
	t.Helper()
	lines := strings.Count(string(src), "\n") + 1
	for i, f := range got {
		if !knownRules[f.Rule] || f.Message == "" {
			t.Fatalf("finding %d = %+v: unknown rule or empty message", i, f)
		}
		if f.Line < 1 || f.Line > lines {
			t.Fatalf("finding %d line %d is outside 1..%d", i, f.Line, lines)
		}
		if i > 0 && (got[i-1].Line > f.Line || (got[i-1].Line == f.Line && got[i-1].Rule > f.Rule)) {
			t.Fatalf("findings are not sorted by line then rule: %+v before %+v", got[i-1], f)
		}
	}
}

func FuzzCheck(f *testing.F) {
	for _, seed := range []string{
		"",
		"---",
		"---\ntitle: x\n---\nWe utilize it.\n",
		"We utilize it, e.g. here. " + sentence(30) + "\n",
		"`code` ``a ` b`` `open\n",
		"<!-- c --> <span a>t</span> <br/> <https://x.y> <foo> < x <!-- open\n",
		"[a [b] c](d) [e][f] [g]( [h \\[i](j) \\` \\<\\\n",
		"| a \\| b | `c|d` |\n|---|:-:|\n| x | y |\n",
		"> “Quoted.” text\n> more\n\n> plain quote via it\n",
		"```go\nfmt.Println()\n```\n~~~\nx\n~~~\n",
		"<div\nskipped\n\nText.\n***\n- - -\nT\n===\n1. step\n- [x] done\n",
		"<!-- GENERATED: x BEGIN -->\nskip\n<!-- GENERATED: x END -->\n",
		"<!-- Code generated. DO NOT EDIT. -->\nx\n",
		"café naïve 日本語. " + strings.Repeat("é ", 40) + "\r\n",
	} {
		f.Add(seed)
	}
	f.Fuzz(func(t *testing.T, doc string) {
		opt := stelint.Options{Words: houseWords}

		got := stelint.Check([]byte(doc), opt)
		again := stelint.Check([]byte(doc), opt)

		if !reflect.DeepEqual(got, again) {
			t.Fatalf("Check is not deterministic:\n%+v\n%+v", got, again)
		}
		assertFindingInvariants(t, []byte(doc), got)
		for _, finding := range stelint.Check([]byte(doc), stelint.Options{}) {
			if finding.Rule == stelint.RuleWord {
				t.Fatalf("an empty word list found a word: %+v", finding)
			}
		}
	})
}

func FuzzCheckGo(f *testing.F) {
	for _, seed := range []string{
		"package p\n",
		goFile(goImports, "\t_ = errors.New(\"we utilize it\")"),
		goFile(goImports, "\t_ = fmt.Errorf(\"go %[1]via %-5.2f %% 100% %[x]d\", s)"),
		goFile(goImports, "\tfmt.Fprintln(os.Stderr, (\"a\" + msg))\n\tx.l.Infof(\"via\")") + "\nconst msg = msg2\nconst msg2 = \"we utilize it\"\n",
		"// Code generated by x. DO NOT EDIT.\n\npackage p\n",
		"package p\nfunc {",
	} {
		f.Add(seed)
	}
	f.Fuzz(func(t *testing.T, src string) {
		got, err := stelint.CheckGo([]byte(src), stelint.Options{Words: houseWords})
		if err != nil {
			if got != nil || !strings.HasPrefix(err.Error(), "parse Go source: ") {
				t.Fatalf("CheckGo error = %v with findings %+v; want a parse error and no findings", err, got)
			}
			return
		}
		again, _ := stelint.CheckGo([]byte(src), stelint.Options{Words: houseWords})
		if !reflect.DeepEqual(got, again) {
			t.Fatalf("CheckGo is not deterministic:\n%+v\n%+v", got, again)
		}
		assertFindingInvariants(t, []byte(src), got)
	})
}
