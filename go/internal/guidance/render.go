package guidance

import (
	"encoding/json"
	"fmt"
	"strings"
)

const (
	IndexMarkdownPath = "guidance/index.md"
	indexJSONPath     = "guidance/index.json"
	IndexFileSchema   = "evolve.guidance.index-file/1"
	EntryKindRule     = "rule"
	L0Begin           = "<!-- GENERATED:guidance-l0 BEGIN"
	L0End             = "<!-- GENERATED:guidance-l0 END -->"
	PointerLine       = "The full rule set is in [guidance/index.md](guidance/index.md). Run `evolve guidance index --audience <you>` to list the rules of your case."
	none              = "—"
)

var layerTitles = map[string]string{
	"L0": "L0 Invariants",
	"L1": "L1 Role",
	"L2": "L2 Situation",
	"L3": "L3 Reference",
	"L4": "L4 Enforcement",
}

type IndexRow struct {
	ID         string   `json:"id"`
	Layer      string   `json:"layer"`
	Kind       string   `json:"kind"`
	Summary    string   `json:"summary"`
	Bytes      int      `json:"bytes"`
	Path       string   `json:"path"`
	Audience   []string `json:"audience"`
	Families   []string `json:"families"`
	Phases     []string `json:"phases"`
	Triggers   Triggers `json:"triggers"`
	EnforcedBy []string `json:"enforced_by"`
}

type indexFile struct {
	Schema  string     `json:"schema"`
	Entries []IndexRow `json:"entries"`
}

func Rows(rules []Rule) []IndexRow {
	rows := []IndexRow{}
	for _, r := range rules {
		rows = append(rows, IndexRow{
			ID:         r.ID,
			Layer:      r.Layer,
			Kind:       EntryKindRule,
			Summary:    r.Statement,
			Bytes:      r.Bytes,
			Path:       BodyPath(r.ID),
			Audience:   nonNil(r.Audience),
			Families:   nonNil(r.Families),
			Phases:     nonNil(r.Phases),
			Triggers:   Triggers{Paths: nonNil(r.Triggers.Paths), Actions: nonNil(r.Triggers.Actions), Tasks: nonNil(r.Triggers.Tasks), Failures: nonNil(r.Triggers.Failures)},
			EnforcedBy: nonNil(r.EnforcedBy),
		})
	}
	return rows
}

func nonNil(s []string) []string {
	if s == nil {
		return []string{}
	}
	return s
}

func IndexJSON(rules []Rule) string {
	out, _ := json.MarshalIndent(indexFile{Schema: IndexFileSchema, Entries: Rows(Active(rules))}, "", "  ")
	return string(out) + "\n"
}

func IndexMarkdown(rules []Rule) string {
	var b strings.Builder
	b.WriteString("<!-- GENERATED by `evolve guidance build` from guidance/rules/; edit a rule file, not this file -->\n# Rule index\n\n")
	b.WriteString("Each row is one active rule of the registry. Open the body of a rule when your task needs it. `evolve guidance index --json` prints the same rows, and its flags filter them.\n")
	b.WriteString(RowsMarkdown(Active(rules), "rules/"))
	return b.String()
}

func RowsMarkdown(rules []Rule, linkBase string) string {
	var b strings.Builder
	layer := ""
	for _, r := range rules {
		if r.Layer != layer {
			layer = r.Layer
			fmt.Fprintf(&b, "\n## %s\n\n| Id | Summary | Audience | Families | Triggers | Enforced by |\n|---|---|---|---|---|---|\n", layerTitles[layer])
		}
		fmt.Fprintf(&b, "| [%s](%s%s.md) | %s | %s | %s | %s | %s |\n", r.ID, linkBase, r.ID, cell(r.Statement), list(r.Audience, "all"), list(r.Families, "all"), triggerCell(r.Triggers), codeList(r.EnforcedBy))
	}
	return b.String()
}

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

func list(items []string, empty string) string {
	if len(items) == 0 {
		return empty
	}
	return cell(strings.Join(items, ", "))
}

func codeList(items []string) string {
	if len(items) == 0 {
		return none
	}
	return "`" + cell(strings.Join(items, "`, `")) + "`"
}

func triggerCell(t Triggers) string {
	var parts []string
	for _, kind := range []struct {
		name  string
		items []string
	}{{"paths", t.Paths}, {"actions", t.Actions}, {"tasks", t.Tasks}, {"failures", t.Failures}} {
		if len(kind.items) > 0 {
			parts = append(parts, kind.name+": "+strings.Join(kind.items, ", "))
		}
	}
	if len(parts) == 0 {
		return none
	}
	return cell(strings.Join(parts, "; "))
}

func L0Block(rules []Rule) string {
	var b strings.Builder
	b.WriteString(L0Begin + " from guidance/rules by `evolve guidance build`; edit the registry, not this region -->\n### Hard rules\n\n")
	for _, r := range Active(rules) {
		if r.Layer != "L0" {
			continue
		}
		fmt.Fprintf(&b, "- %s", r.Statement)
		if len(r.EnforcedBy) > 0 {
			fmt.Fprintf(&b, " (enforced by %s)", codeList(r.EnforcedBy))
		}
		b.WriteString("\n")
	}
	b.WriteString("\n" + PointerLine + "\n" + L0End + "\n")
	return b.String()
}
